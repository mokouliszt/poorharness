/** A host error in the user's language when it is one of the known codes; otherwise as given. */
export function describeError(t: (key: Key) => string, message: string | null | undefined): string {
  const text = message ?? "";
  const hit = ERROR_CODES.find(([code]) => text.includes(code));
  return hit ? t(hit[1]) : text;
}
